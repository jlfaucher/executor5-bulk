                if (status == INDEX_TOO_LARGE) return "Invalid code point index: " + index + " exceeds the code point count " + std::to_string(codepointCount_);
                return "Code point index " + index + " is not stored";
            case GRAPHEME_INDEX_B:
                if (status == ZERO_INDEX) return "Invalid grapheme index: " + index;
                if (status == INDEX_TOO_LARGE) return "Invalid grapheme index: " + index + " exceeds the grapheme count " + std::to_string(graphemeCount());
