/**
 * Direct access to the codepoints and graphemes of a UTF-8 string.
 *
 * The string is NOT copied: the caller must keep it alive and unchanged.
 *
 * Terminology (same as the ooRexx class):
 * - indexC: 1-based codepoint index, indexG: 1-based grapheme index,
 *   indexB: 1-based byte index. A negative indexC/indexG counts from the end.
 * - A byte index returned by the methods is negative when the byte sequence at
 *   this position is invalid (the sign is computed by decoding at that position,
 *   it is not stored).
 *
 * Storage:
 * - start storage: the first N indexes. end storage: the last M indexes.
 *   The end storage never overlaps the start storage.
 * - Six independent limits (start/end x grapheme/codepoint/error).
 *   A limit of 0 disables the storage.
 * - Error messages are not stored: only the position of the invalid byte
 *   sequences is stored, the messages are rebuilt on demand.
 * - incremental: a missing index is stored on demand (with the missing
 *   intermediate indexes), on the side (start or end) that needs the smaller
 *   number of intermediate indexes (start when equal). The error storage is
 *   completed as a side effect of the extension: an invalid byte sequence that
 *   is stored by the extension and is the next error in sequence for the start
 *   (end) error storage is appended to it, beyond the limit. An error that is
 *   already stored, or that would leave a gap, is skipped. So the error storage
 *   always holds the first (last) N errors, without duplicate.
 *
 * Not thread safe. Query methods are not const because they can complete the
 * storage.
 */
